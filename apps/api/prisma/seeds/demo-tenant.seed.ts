import { PrismaClient } from '@prisma/client';
import * as argon2 from 'argon2';

export async function seedDemoTenant(prisma: PrismaClient): Promise<void> {
  if (process.env['NODE_ENV'] === 'production') {
    console.log('⚠ Skipping demo tenant seed in production');
    return;
  }

  const enterprisePlan = await prisma.saasPlan.findUnique({
    where: { slug: 'enterprise' },
  });
  if (!enterprisePlan) throw new Error('Enterprise plan not found — run plans seed first');

  const copCurrency = await prisma.currency.findUnique({ where: { code: 'COP' } });
  const usdCurrency = await prisma.currency.findUnique({ where: { code: 'USD' } });
  if (!copCurrency || !usdCurrency) throw new Error('Currencies not found');

  // ── Super Admin (plataforma) ────────────────────────────────
  const superAdminEmail = process.env['SUPER_ADMIN_EMAIL'] ?? 'admin@inventario.dev';
  const superAdminPwd = process.env['SUPER_ADMIN_PASSWORD'] ?? 'Admin123!';

  let superAdminTenant = await prisma.tenant.findUnique({ where: { slug: 'sistema' } });
  if (!superAdminTenant) {
    superAdminTenant = await prisma.tenant.create({
      data: {
        name: 'Sistema Inventario SaaS',
        slug: 'sistema',
        email: superAdminEmail,
        status: 'active',
        planId: enterprisePlan.id,
        settings: {},
      },
    });
  }

  const superAdminRole = await prisma.role.findFirst({ where: { slug: 'super_admin', tenantId: null } });
  if (!superAdminRole) throw new Error('Super admin role not found');

  const superAdminHash = await argon2.hash(superAdminPwd, { type: argon2.argon2id });
  const superAdminUser = await prisma.user.upsert({
    where: { tenantId_email: { tenantId: superAdminTenant.id, email: superAdminEmail } },
    update: {},
    create: {
      tenantId: superAdminTenant.id,
      email: superAdminEmail,
      passwordHash: superAdminHash,
      firstName: 'Super',
      lastName: 'Admin',
      status: 'active',
      emailVerifiedAt: new Date(),
    },
  });

  const existingSuperAdminRole = await prisma.userRole.findFirst({
    where: { userId: superAdminUser.id, roleId: superAdminRole.id, branchId: null },
  });
  if (!existingSuperAdminRole) {
    await prisma.userRole.create({ data: { userId: superAdminUser.id, roleId: superAdminRole.id } });
  }

  // ── Demo Tenant ─────────────────────────────────────────────
  let demoTenant = await prisma.tenant.findUnique({ where: { slug: 'demo-empresa' } });
  if (!demoTenant) {
    demoTenant = await prisma.tenant.create({
      data: {
        name: 'Empresa Demo',
        slug: 'demo-empresa',
        legalName: 'Empresa Demo S.A.S.',
        taxId: '900123456-1',
        email: 'demo@empresa.com',
        phone: '+57 300 000 0000',
        address: { street: 'Calle 100 #15-30', city: 'Bogotá', country: 'Colombia' },
        status: 'active',
        planId: enterprisePlan.id,
        settings: {
          timezone: 'America/Bogota',
          locale: 'es-CO',
          currency: 'COP',
          dateFormat: 'DD/MM/YYYY',
          timeFormat: '12h',
          fiscalYearStartMonth: 1,
          requireInvoice: false,
          allowNegativeStock: false,
          requirePurchaseApproval: true,
          purchaseApprovalThreshold: 1000000,
          lowStockAlertEnabled: true,
          autoGenerateDailyReport: true,
          reportGenerationTime: '23:55',
          maxDiscountPercent: 30,
          requireSaleDiscount: false,
        },
      },
    });
  }

  // SaaS Subscription para demo tenant
  await prisma.saasSubscription.upsert({
    where: { tenantId: demoTenant.id },
    update: {},
    create: {
      tenantId: demoTenant.id,
      planId: enterprisePlan.id,
      status: 'active',
      billingCycle: 'annual',
      startedAt: new Date(),
      currentPeriodStart: new Date(),
      currentPeriodEnd: new Date(Date.now() + 365 * 24 * 60 * 60 * 1000),
    },
  });

  // Currencies para demo tenant
  await prisma.tenantCurrency.createMany({
    data: [
      { tenantId: demoTenant.id, currencyId: copCurrency.id, isDefault: true },
      { tenantId: demoTenant.id, currencyId: usdCurrency.id },
    ],
    skipDuplicates: true,
  });

  // Sucursales demo
  const mainBranch = await prisma.branch.upsert({
    where: { tenantId_code: { tenantId: demoTenant.id, code: 'PRINCIPAL' } },
    update: {},
    create: {
      tenantId: demoTenant.id,
      name: 'Sucursal Principal',
      code: 'PRINCIPAL',
      type: 'physical',
      address: { street: 'Calle 100 #15-30', city: 'Bogotá', country: 'Colombia' },
      phone: '+57 300 000 0001',
      email: 'principal@empresa.com',
      isActive: true,
    },
  });

  await prisma.branch.upsert({
    where: { tenantId_code: { tenantId: demoTenant.id, code: 'NORTE' } },
    update: {},
    create: {
      tenantId: demoTenant.id,
      name: 'Sucursal Norte',
      code: 'NORTE',
      type: 'physical',
      address: { street: 'Cra 15 #80-45', city: 'Bogotá', country: 'Colombia' },
      isActive: true,
    },
  });

  // Usuarios demo
  const demoPassword = await argon2.hash('Demo123!', { type: argon2.argon2id });

  const adminRole = await prisma.role.findFirst({ where: { slug: 'admin_general', tenantId: null } });
  const sellerRole = await prisma.role.findFirst({ where: { slug: 'seller', tenantId: null } });
  const supervisorRole = await prisma.role.findFirst({ where: { slug: 'supervisor', tenantId: null } });

  const demoUsers = [
    { email: 'admin@empresa.com', firstName: 'Carlos', lastName: 'Admin', role: adminRole },
    { email: 'vendedor@empresa.com', firstName: 'María', lastName: 'Vendedora', role: sellerRole },
    { email: 'supervisor@empresa.com', firstName: 'Pedro', lastName: 'Supervisor', role: supervisorRole },
  ];

  for (const u of demoUsers) {
    if (!u.role) continue;
    const user = await prisma.user.upsert({
      where: { tenantId_email: { tenantId: demoTenant.id, email: u.email } },
      update: {},
      create: {
        tenantId: demoTenant.id,
        email: u.email,
        passwordHash: demoPassword,
        firstName: u.firstName,
        lastName: u.lastName,
        status: 'active',
        emailVerifiedAt: new Date(),
      },
    });
    const existingUserRole = await prisma.userRole.findFirst({
      where: { userId: user.id, roleId: u.role.id, branchId: null },
    });
    if (!existingUserRole) {
      await prisma.userRole.create({ data: { userId: user.id, roleId: u.role.id } });
    }
  }

  // Caja registradora demo
  await prisma.cashRegister.upsert({
    where: { tenantId_branchId_code: { tenantId: demoTenant.id, branchId: mainBranch.id, code: 'CAJA-01' } },
    update: {},
    create: {
      tenantId: demoTenant.id,
      branchId: mainBranch.id,
      name: 'Caja Principal 1',
      code: 'CAJA-01',
      isActive: true,
    },
  });

  // Categorías demo
  const categoriaRoot = await prisma.category.upsert({
    where: { tenantId_slug: { tenantId: demoTenant.id, slug: 'productos' } },
    update: {},
    create: {
      tenantId: demoTenant.id,
      name: 'Productos',
      slug: 'productos',
      sortOrder: 1,
    },
  });

  await prisma.category.createMany({
    data: [
      { tenantId: demoTenant.id, parentId: categoriaRoot.id, name: 'Electrónicos', slug: 'electronicos', sortOrder: 1 },
      { tenantId: demoTenant.id, parentId: categoriaRoot.id, name: 'Ropa y Accesorios', slug: 'ropa-accesorios', sortOrder: 2 },
      { tenantId: demoTenant.id, parentId: categoriaRoot.id, name: 'Joyería', slug: 'joyeria', sortOrder: 3 },
      { tenantId: demoTenant.id, parentId: categoriaRoot.id, name: 'Alimentos', slug: 'alimentos', sortOrder: 4 },
    ],
    skipDuplicates: true,
  });

  console.log('✓ Demo tenant seeded');
  console.log(`  Super Admin: ${superAdminEmail} / ${superAdminPwd}`);
  console.log(`  Demo Admin:  admin@empresa.com / Demo123!`);
  console.log(`  Demo Seller: vendedor@empresa.com / Demo123!`);
}
